-- =====================================================================================
-- 01_schema.sql  -  Normalized (3NF) PostgreSQL schema for HospitalDB
-- -------------------------------------------------------------------------------------
-- PostgreSQL port of the MySQL prototype (hospital_data_migration.sql, database EHIAS).
--
-- Schemas
--   hospital   : the 9 normalized operational tables
--                (7 migrated from the legacy extract + wards/admissions inpatient module)
--   auth       : doctor login credentials (bcrypt-hashed, never plaintext)
--   etl        : staging, run log, data-quality log, quarantine (see 03_etl.sql)
--   analytics  : reporting views (see 05_views.sql)
-- =====================================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- bcrypt hashing for credentials

CREATE SCHEMA IF NOT EXISTS hospital;
CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS etl;
CREATE SCHEMA IF NOT EXISTS analytics;

SET search_path = hospital, public;

-- 1. Departments ----------------------------------------------------------------------
CREATE TABLE hospital.departments (
    department_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50) NOT NULL UNIQUE
);

-- 2. Doctors --------------------------------------------------------------------------
CREATE TABLE hospital.doctors (
    doctor_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50)  NOT NULL,
    specialization  VARCHAR(100) NOT NULL,
    role            VARCHAR(20)  NOT NULL
                    CHECK (role IN ('Junior', 'Resident', 'Consultant', 'Senior')),
    department_id   INT NOT NULL REFERENCES hospital.departments (department_id)
);

-- 3. Patients -------------------------------------------------------------------------
CREATE TABLE hospital.patients (
    patient_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50) NOT NULL,
    date_of_birth   DATE        NOT NULL CHECK (date_of_birth > DATE '1900-01-01'),
    gender          CHAR(1)     NOT NULL CHECK (gender IN ('m', 'f', 'o')),
    phone           VARCHAR(15) NOT NULL CHECK (phone ~ '^[0-9]{10}$')
);

-- 4. Appointments ---------------------------------------------------------------------
CREATE TABLE hospital.appointments (
    appointment_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       INT NOT NULL REFERENCES hospital.patients (patient_id),
    doctor_id        INT NOT NULL REFERENCES hospital.doctors  (doctor_id),
    appointment_time TIMESTAMP   NOT NULL,
    status           VARCHAR(20) NOT NULL
                     CHECK (status IN ('Scheduled', 'Completed', 'Cancelled'))
);

-- 5. Prescriptions --------------------------------------------------------------------
CREATE TABLE hospital.prescriptions (
    prescription_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   INT NOT NULL REFERENCES hospital.appointments (appointment_id),
    medication       VARCHAR(100) NOT NULL,
    dosage           VARCHAR(50)  NOT NULL,
    -- the same drug must not be prescribed twice on one visit (source had duplicates)
    CONSTRAINT uq_prescription_per_visit UNIQUE (appointment_id, medication)
);

-- 6. Bills ----------------------------------------------------------------------------
CREATE TABLE hospital.bills (
    bill_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   INT NOT NULL REFERENCES hospital.appointments (appointment_id),
    amount           NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    paid             BOOLEAN   NOT NULL DEFAULT FALSE,
    bill_date        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Lab reports (raw JSON text in the legacy file -> validated JSONB) ------------------
CREATE TABLE hospital.lab_reports (
    report_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   INT NOT NULL REFERENCES hospital.appointments (appointment_id),
    report_data      JSONB     NOT NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 8. Wards (inpatient module) ---------------------------------------------------------
CREATE TABLE hospital.wards (
    ward_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_name        VARCHAR(50) NOT NULL UNIQUE,
    department_id    INT NOT NULL REFERENCES hospital.departments (department_id),
    ward_type        VARCHAR(20) NOT NULL CHECK (ward_type IN ('General', 'HDU')),
    bed_capacity     INT NOT NULL CHECK (bed_capacity > 0)
);

-- 9. Admissions (an inpatient stay that originates from a completed appointment) -------
--    patient is reached through the appointment -> no transitive duplication (3NF)
CREATE TABLE hospital.admissions (
    admission_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   INT NOT NULL UNIQUE REFERENCES hospital.appointments (appointment_id),
    ward_id          INT NOT NULL REFERENCES hospital.wards (ward_id),
    admitted_at      TIMESTAMP NOT NULL,
    discharged_at    TIMESTAMP,                       -- NULL = still in a bed
    CONSTRAINT ck_discharge_after_admit CHECK (discharged_at IS NULL OR discharged_at > admitted_at)
);

-- Credentials (kept outside the clinical schema) --------------------------------------
CREATE TABLE auth.doctor_credentials (
    doctor_id        INT PRIMARY KEY REFERENCES hospital.doctors (doctor_id) ON DELETE CASCADE,
    username         VARCHAR(50) NOT NULL UNIQUE,
    password_hash    TEXT        NOT NULL              -- bcrypt via pgcrypto crypt()
);
